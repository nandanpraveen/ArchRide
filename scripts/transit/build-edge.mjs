import { readFile, writeFile } from "node:fs/promises";
// Bundle the shared worker, not a second implementation. Runtime packages are version-pinned in deno.json.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { build } = require(
  require.resolve("esbuild", { paths: [require.resolve("tsx")] }),
);
await build({
  entryPoints: ["scripts/transit/run.ts"],
  outfile: "supabase/functions/transit-ingest/core.js",
  bundle: true,
  platform: "neutral",
  format: "esm",
  packages: "external",
  target: "es2022",
  banner: {
    js: "// Generated by pnpm transit:edge:build. Do not edit; source is scripts/transit/run.ts.",
  },
});
await build({
  entryPoints: ["src/lib/predictor.ts"],
  outfile: "supabase/functions/predictor-update/core.js",
  bundle: true,
  platform: "neutral",
  format: "esm",
  target: "es2022",
  banner: {
    js: "// Generated by pnpm transit:edge:build. Source: src/lib/predictor.ts.",
  },
});

await writeFile(
  "supabase/functions/predictor-update/dataset.js",
  "// Generated from scripts/transit/predictor-dataset.sql.\nconst datasetQuery = " +
    JSON.stringify(
      await readFile("scripts/transit/predictor-dataset.sql", "utf8"),
    ) +
    ";\nexport default datasetQuery;\n",
);
