// Generate from the migrated PostgreSQL catalog, never from a handwritten type approximation.
import { writeFile } from "node:fs/promises";
import { localDatabase } from "./local-db";
async function main() {
  const { db, engine } = await localDatabase();
  try {
    const tables = (
      await db.query<{ table_name: string }>(
        "select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by table_name",
      )
    ).rows;
    const fields: string[] = [];
    for (const { table_name: table } of tables) {
      const columns = (
        await db.query<{
          column_name: string;
          is_nullable: string;
          column_default: string | null;
          data_type: string;
          udt_name: string;
        }>(
          "select column_name,is_nullable,column_default,data_type,udt_name from information_schema.columns where table_schema='public' and table_name=$1 order by ordinal_position",
          [table],
        )
      ).rows;
      const type = (c: (typeof columns)[number]) => {
        const t =
          c.data_type === "ARRAY"
            ? c.udt_name === "_int2" || c.udt_name === "_int4"
              ? "number[]"
              : "string[]"
            : c.data_type === "boolean"
              ? "boolean"
              : [
                    "integer",
                    "bigint",
                    "smallint",
                    "double precision",
                    "numeric",
                    "real",
                  ].includes(c.data_type)
                ? "number"
                : c.udt_name === "jsonb"
                  ? "Json"
                  : "string";
        return t + (c.is_nullable === "YES" ? " | null" : "");
      };
      const relations = (
        await db.query<{
          name: string;
          cols: string[];
          target: string;
          target_cols: string[];
        }>(
          `select con.conname as name,
    array(select attname from unnest(con.conkey) with ordinality k(n,o) join pg_attribute a on a.attrelid=con.conrelid and a.attnum=k.n order by k.o) as cols,
    cl.relname as target,
    array(select attname from unnest(con.confkey) with ordinality k(n,o) join pg_attribute a on a.attrelid=con.confrelid and a.attnum=k.n order by k.o) as target_cols
    from pg_constraint con join pg_class own on own.oid=con.conrelid join pg_namespace ns on ns.oid=own.relnamespace join pg_class cl on cl.oid=con.confrelid
    where con.contype='f' and ns.nspname='public' and own.relname=$1`,
          [table],
        )
      ).rows;
      fields.push(
        `${table}: {\n${(["Row", "Insert", "Update"] as const).map((mode) => `${mode}: {\n${columns.map((c) => `${c.column_name}${mode === "Update" || (mode === "Insert" && (c.is_nullable === "YES" || c.column_default !== null)) ? "?" : ""}: ${type(c)};`).join("\n")}\n};`).join("\n")}\nRelationships: [${relations.map((r) => `{foreignKeyName: ${JSON.stringify(r.name)}; columns: ${JSON.stringify(r.cols)}; isOneToOne: false; referencedRelation: ${JSON.stringify(r.target)}; referencedColumns: ${JSON.stringify(r.target_cols)};}`).join(",")}];\n};`,
      );
    }
    const routines = (
      await db.query<{
        name: string;
        names: string[];
        types: string[];
        returns: string;
      }>(
        `select p.proname as name,p.proargnames as names,array(select format_type(t,null) from unnest(p.proargtypes::oid[]) t) as types,format_type(p.prorettype,null) as returns from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prorettype <> 'trigger'::regtype order by p.proname`,
      )
    ).rows;
    const routineType = (t: string): string =>
      t.endsWith("[]")
        ? routineType(t.slice(0, -2)) + "[]"
        : t === "void"
          ? "undefined"
          : t === "boolean"
            ? "boolean"
            : [
                  "smallint",
                  "integer",
                  "bigint",
                  "real",
                  "double precision",
                  "numeric",
                ].includes(t)
              ? "number"
              : t === "jsonb" || t === "json"
                ? "Json"
                : "string";
    const functions = routines
      .map(
        (r) =>
          `${JSON.stringify(r.name)}: { Args: { ${r.types.map((t, i) => `${JSON.stringify(r.names[i])}: ${routineType(t)}`).join("; ")} }; Returns: ${routineType(r.returns)} }`,
      )
      .join(";\n");
    await writeFile(
      "src/lib/supabase/database.types.ts",
      `// Generated by pnpm db:types:local from all checked-in migrations.\n// For hosted schema verification, use pnpm db:types after applying migrations.\nexport type Json = string | number | boolean | null | { [key:string]:Json|undefined } | Json[];\nexport type Database = { __InternalSupabase: { PostgrestVersion: "14.18" }; public: { Tables: {\n${fields.join("\n")}\n}; Views: Record<never,never>; Functions: {${functions}}; Enums: Record<never,never>; CompositeTypes: Record<never,never>; }; };\nexport type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];\nexport type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];\nexport type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update'];\nexport const Constants = {public:{Enums:{}}} as const;\n`,
    );
  } finally {
    await engine.close();
  }
}
main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
